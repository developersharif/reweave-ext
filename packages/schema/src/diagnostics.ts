export type DiagnosticCode = (typeof CODES)[keyof typeof CODES];

export interface Diagnostic {
  code: DiagnosticCode;
  severity: Severity;
  message: string;
  /** Dot path into a manifest (e.g. `settings.2.default`) */
  path?: string;
  /** Source file for CSS diagnostics (e.g. `styles/watch.css`) */
  file?: string;
  line?: number;
  column?: number;
}

export const hasErrors = (diagnostics: readonly Diagnostic[]): boolean =>
  diagnostics.some((d) => d.severity === 'error');

export function diag(
  code: DiagnosticCode,
  severity: Severity,
  message: string,
  extra: Omit<Diagnostic, 'code' | 'severity' | 'message'> = {},
): Diagnostic {
  return { code, severity, message, ...extra };
}
